# --- регионы превращения ---
OFF = 900
RS = 1.7   # шаг колец регионов
chains = {}
def make_region(rid, ang, rname, color, pool, notables, key, asc_branches, spread=6.0, side_notable=15.0):
    chain = []
    radii = [200, 255, 310, 365, 420, 475, 530, 585, 640]
    for i, r in enumerate(radii):
        x, y = pol(r * RS + OFF, ang)
        if i in (3, 6):
            nm, mods = notables[0 if i == 3 else 1]
            nid = add(nm, "notable", x, y, rid, mods, max_rank=2)
        else:
            st, v, nm = pool[i % len(pool)]
            nid = add(nm, "minor", x, y, rid, [(st, v)], max_rank=3)
        if chain: link(chain[-1], nid)
        chain.append(nid)
    link(outer[ang], chain[0])
    for base_i, side_r in ((2, 310), (5, 475)):
        for side in (-1, 1):
            prev = chain[base_i]
            for k in range(1, 3):
                x, y = pol(side_r * RS + OFF, ang + side * k * spread)
                st, v, nm = pool[(k + base_i + side) % len(pool)]
                nid = add(nm, "minor", x, y, rid, [(st, v)], max_rank=3)
                link(prev, nid); prev = nid
            if base_i == 5 and side == 1:
                x, y = pol(side_r * RS + OFF + 80, ang + side * side_notable)
                nm, mods = notables[2]
                nid = add(nm, "notable", x, y, rid, mods, max_rank=2); link(prev, nid)
    x, y = pol(700 * RS + OFF, ang)
    sup = rid in SUPPORT
    gate = add(key[0], "keystone", x, y, rid, key[1], gate=True,
               desc="Ворота превращения: открывает путь «%s»%s" % (rname, " (поддержка)" if sup else ""))
    link(chain[-1], gate)
    chains[rid] = chain
    # ветви пути (только для выбравших это превращение)
    for bi, (bname, minor, notable, keyst) in enumerate(asc_branches):
        a = ang + (bi - 1) * 7
        bid = f"{rid}_{bi}"
        x, y = pol(700 * RS + OFF + 130, a)
        n1 = add(bname, "minor", x, y, rid, [minor], "", bid, 3, {}, rid)
        nodes[n1]["branch_name"] = bname
        x, y = pol(700 * RS + OFF + 250, a)
        n2 = add(notable[0], "notable", x, y, rid, notable[1], "", bid, 2, notable[2], rid)
        x, y = pol(700 * RS + OFF + 380, a)
        n3 = add(keyst[0], "keystone", x, y, rid, keyst[1], "", bid, 1, keyst[2], rid, 4, desc=keyst[3])
        link(gate, n1); link(n1, n2); link(n2, n3)

